export const formatRupiah = (value) =>
    `Rp${new Intl.NumberFormat('id-ID').format(value)}`;

export const formatCompactRupiah = (value) => {
    if (value >= 1000000) {
        return `Rp${(value / 1000000).toLocaleString('id-ID', {
            maximumFractionDigits: 2,
        })} jt`;
    }

    return formatRupiah(value);
};

export const initialsOf = (name) => {
    const parts = String(name ?? '')
        .trim()
        .split(/\s+/)
        .filter(Boolean);

    if (parts.length === 0) {
        return 'CL';
    }

    return parts
        .slice(0, 2)
        .map((part) => part[0])
        .join('')
        .toUpperCase();
};

export const whatsappLink = (phone) => {
    const digits = String(phone ?? '').replace(/\D/g, '');

    if (!digits) {
        return null;
    }

    return `https://wa.me/${
        digits.startsWith('0') ? `62${digits.slice(1)}` : digits
    }`;
};
